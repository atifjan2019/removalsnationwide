/**
 * Custom Worker entry for removals-nationwide: a thin edge HTML cache in front
 * of the OpenNext handler.
 *
 * The (site) layout is force-dynamic on purpose (contact details and branding
 * come from D1 on every request), so every public page view used to run a full
 * Next render inside the Worker. This wrapper serves anonymous GET/HEAD page
 * requests from the Cache API. A hit never touches the Next server bundle: it
 * costs one D1 point read (I/O), one cache.match (I/O) and a header copy.
 *
 * Keys are versioned instead of purged, because cache.delete() only clears the
 * local data centre:
 *   - deploy version  -> env.CF_VERSION_METADATA.id (version_metadata binding)
 *   - content version -> site_cache_version.v in D1, bumped by every admin save
 *                        that changes public pages (src/lib/public-cache.ts)
 */

// Generated by `opennextjs-cloudflare build`. Absent before the first build,
// so the type checker is told to skip it (this file is excluded in tsconfig).
// @ts-ignore
import openNext from "./.open-next/worker.js";

// Parity with the stock entry (no DO bindings use these today).
// @ts-ignore
export { DOQueueHandler, DOShardedTagCache, BucketCachePurge } from "./.open-next/worker.js";

type Env = {
  DB: D1Database;
  CF_VERSION_METADATA?: WorkerVersionMetadata;
  [binding: string]: unknown;
};

const CANONICAL_HOST = "removalsnationwide.uk";
const EDGE_TTL_OK = 60 * 60 * 24; // 200 pages: one day (keys are versioned; TTL only bounds stale-on-failure)
const EDGE_TTL_NOT_FOUND = 60 * 60; // 404 pages: one hour (old WordPress URLs, bots)
const BROWSER_CACHE_CONTROL = "public, max-age=0, must-revalidate";
const VERSION_MEMO_MS = 1000; // 0 = read D1 on every cacheable request
const RSC_MODE: "mpa" | "passthrough" = "mpa";
/** Same fallback as src/app/brand-icon/route.ts. Keep the two in step. */
const FAVICON_FALLBACK =
  "https://media.removalsnationwide.uk/public/images/brand/removals-nationwide-logo.png";

const NEVER_CACHE_PREFIXES = [
  "/admin", // also covers /admin-login
  "/api/",
  "/move-details/",
  "/bookservice/",
  "/brand-icon/",
  "/_next/",
  "/cdn-cgi/",
  "/.well-known/",
];
const RSC_PASSTHROUGH_PREFIXES = ["/admin", "/api/"];
const BYPASS_COOKIES = ["rn_admin_session=", "__prerender_bypass=", "__next_preview_data="];
const TRACKING_PARAMS = new Set([
  "gclid", "gbraid", "wbraid", "gad_source", "gad_campaignid", "dclid", "srsltid",
  "fbclid", "msclkid", "ttclid", "twclid", "li_fat_id", "yclid", "igshid",
  "mc_cid", "mc_eid", "_ga", "_gl", "ref",
]);
const ALLOWED_QUERY: Record<string, Record<string, RegExp>> = {
  "/news/": { page: /^[1-9]\d{0,3}$/ },
};

let versionMemo: { value: string; at: number } | null = null;

export default {
  async fetch(request: Request, env: Env, ctx: ExecutionContext): Promise<Response> {
    const url = new URL(request.url);
    const method = request.method;
    const isRead = method === "GET" || method === "HEAD";

    // 1. http -> https (backstop; also enable the zone's "Always Use HTTPS").
    if (
      url.protocol === "http:" &&
      url.hostname === CANONICAL_HOST &&
      request.headers.get("x-forwarded-proto") !== "https"
    ) {
      url.protocol = "https:";
      return redirect(url.toString(), isRead ? 301 : 308, "https");
    }

    // 2. Writes always reach Next. An admin write may have bumped the version.
    if (!isRead) {
      const res = await openNext.fetch(request, env, ctx);
      if (url.pathname.startsWith("/admin")) versionMemo = null;
      return label(res, "BYPASS:write");
    }

    const path = url.pathname;

    // 3. Favicon redirect from one D1 read instead of booting the Next server.
    if (path === "/brand-icon/") {
      const icon = await brandIcon(env);
      return icon ?? pass(request, env, ctx, "brand-icon");
    }

    // 4. Client-router (RSC) requests.
    const isRsc = request.headers.get("rsc") === "1" || url.searchParams.has("_rsc");
    if (isRsc) {
      if (RSC_MODE === "mpa" && !startsWithAny(path, RSC_PASSTHROUGH_PREFIXES)) {
        const isPrefetch = request.headers.has("next-router-prefetch");
        if (isPrefetch || !startsWithAny(path, NEVER_CACHE_PREFIXES)) return rscFallback();
      }
      return pass(request, env, ctx, "rsc");
    }

    // 5. Requests that must not share a cached answer. Slashless page paths fall
    //    through here, and OpenNext's own trailingSlash rule redirects them.
    if (!path.endsWith("/")) return pass(request, env, ctx, "file");
    if (startsWithAny(path, NEVER_CACHE_PREFIXES)) return pass(request, env, ctx, "path");
    const cookie = request.headers.get("cookie");
    if (cookie && BYPASS_COOKIES.some((name) => cookie.includes(name))) {
      return pass(request, env, ctx, "cookie");
    }
    if (request.headers.has("authorization") || request.headers.has("range")) {
      return pass(request, env, ctx, "header");
    }
    const query = normaliseQuery(url);
    if (!query) return pass(request, env, ctx, "query");

    // 6. Versions. Without either one we cannot key safely, so render instead.
    const deployVersion = env.CF_VERSION_METADATA?.id;
    if (!deployVersion) return pass(request, env, ctx, "no-version-binding");
    const contentVersion = await readContentVersion(env);
    if (contentVersion === null) return pass(request, env, ctx, "version-read-failed");

    const etag = `W/"rn-${deployVersion.slice(0, 13)}-${contentVersion}"`;

    // 7. Browser revalidation: same deploy + same content = same page.
    const ifNoneMatch = request.headers.get("if-none-match");
    if (ifNoneMatch && ifNoneMatch.split(",").some((t) => t.trim() === etag)) {
      return new Response(null, {
        status: 304,
        headers: { ETag: etag, "Cache-Control": BROWSER_CACHE_CONTROL, "x-rn-cache": "REVALIDATED" },
      });
    }

    // 8. Edge lookup with a header-less key.
    const sep = query.search ? "&" : "?";
    const cacheKey = new Request(
      `${url.origin}${path}${query.search}${sep}__rnv=${encodeURIComponent(deployVersion)}.${contentVersion}`,
    );
    const cache = caches.default;
    let hit: Response | undefined;
    try {
      hit = await cache.match(cacheKey);
    } catch (err) {
      console.error("[edge-cache] match failed", err);
    }
    if (hit) return serveStored(hit, method === "HEAD", etag);

    // 9. Miss: render once (clean URL, GET), answer, store a copy in the background.
    const renderHeaders = new Headers(request.headers);
    renderHeaders.delete("if-none-match");
    renderHeaders.delete("if-modified-since");
    const renderRequest = new Request(`${url.origin}${path}${query.search}`, {
      method: "GET",
      headers: renderHeaders,
      redirect: "manual",
      cf: (request as Request & { cf?: unknown }).cf,
    } as RequestInit);

    // The render gets its own context object: the D1 loaders set rnDegraded on
    // it (markDegraded in src/lib/d1.ts) when they fall back to defaults, and
    // such a page is served but never stored.
    const renderCtx = {
      waitUntil: (promise: Promise<unknown>) => ctx.waitUntil(promise),
      passThroughOnException: () => ctx.passThroughOnException(),
      props: (ctx as ExecutionContext & { props?: unknown }).props,
      rnDegraded: false,
    };
    const res = await openNext.fetch(renderRequest, env, renderCtx);
    if (!isStorable(res)) return label(res, "MISS:uncacheable");

    const [forVisitor, forCache] = res.body!.tee();

    const stored = new Headers(res.headers);
    const nextVary = stored.get("vary");
    stored.delete("vary");
    stored.delete("set-cookie");
    if (nextVary) stored.set("x-rn-vary", nextVary);
    stored.set("cache-control", `public, max-age=${res.status === 200 ? EDGE_TTL_OK : EDGE_TTL_NOT_FOUND}`);
    stored.set("etag", etag);
    ctx.waitUntil(
      (async () => {
        // Loaders run while the body streams, so decide only once it is complete.
        const body = await new Response(forCache).arrayBuffer();
        if (renderCtx.rnDegraded) {
          console.warn("[edge-cache] not stored: render used fallback data", path);
          return;
        }
        await cache.put(cacheKey, new Response(body, { status: res.status, statusText: res.statusText, headers: stored }));
      })().catch((err) => console.error("[edge-cache] put failed", err)),
    );

    const out = new Headers(res.headers);
    out.set("cache-control", BROWSER_CACHE_CONTROL);
    out.set("etag", etag);
    out.set("x-rn-cache", "MISS");
    if (method === "HEAD") {
      forVisitor.cancel().catch(() => {});
      return new Response(null, { status: res.status, statusText: res.statusText, headers: out });
    }
    return new Response(forVisitor, { status: res.status, statusText: res.statusText, headers: out });
  },
};

async function pass(request: Request, env: Env, ctx: ExecutionContext, reason: string): Promise<Response> {
  const res: Response = await openNext.fetch(request, env, ctx);
  return label(res, `BYPASS:${reason}`);
}

function label(res: Response, value: string): Response {
  try {
    res.headers.set("x-rn-cache", value);
    return res;
  } catch {
    const copy = new Response(res.body, res);
    copy.headers.set("x-rn-cache", value);
    return copy;
  }
}

function redirect(location: string, status: number, why: string): Response {
  return new Response(null, { status, headers: { Location: location, "x-rn-cache": `REDIRECT:${why}` } });
}

/** Not a flight response: Next's router does an MPA navigation (or treats a prefetch as a miss). */
function rscFallback(): Response {
  return new Response(null, { status: 204, headers: { "Cache-Control": "no-store", "x-rn-cache": "RSC-MPA" } });
}

function serveStored(hit: Response, head: boolean, etag: string): Response {
  const headers = new Headers(hit.headers);
  const vary = headers.get("x-rn-vary");
  headers.delete("x-rn-vary");
  if (vary) headers.set("vary", vary);
  headers.set("cache-control", BROWSER_CACHE_CONTROL);
  headers.set("etag", etag);
  headers.set("x-rn-cache", "HIT");
  if (head) {
    hit.body?.cancel().catch(() => {});
    return new Response(null, { status: hit.status, statusText: hit.statusText, headers });
  }
  return new Response(hit.body, { status: hit.status, statusText: hit.statusText, headers });
}

function isStorable(res: Response): boolean {
  if (res.status !== 200 && res.status !== 404) return false;
  if (!res.body) return false;
  const h = res.headers;
  if (h.has("set-cookie")) return false;
  // OpenNext labels uncompressed bodies "identity"; anything else is a real encoding.
  const encoding = (h.get("content-encoding") ?? "identity").trim().toLowerCase();
  if (encoding !== "identity") return false;
  if (!(h.get("content-type") ?? "").toLowerCase().startsWith("text/html")) return false;
  if (/noindex/i.test(h.get("x-robots-tag") ?? "")) return false;
  if (/no-store/i.test(h.get("x-rn-edge-cache") ?? "")) return false;
  if ((h.get("vary") ?? "").trim() === "*") return false;
  return true;
}

async function readContentVersion(env: Env): Promise<string | null> {
  const now = Date.now();
  if (versionMemo && now - versionMemo.at < VERSION_MEMO_MS) return versionMemo.value;
  try {
    const row = await env.DB.prepare("select v from site_cache_version where id = 1").first<{ v: number }>();
    const value = String(row?.v ?? 0);
    versionMemo = { value, at: Date.now() };
    return value;
  } catch (err) {
    console.error("[edge-cache] content version read failed", err);
    return null;
  }
}

async function brandIcon(env: Env): Promise<Response | null> {
  try {
    const row = await env.DB
      .prepare("select favicon_url from settings where id = 'site' limit 1")
      .first<{ favicon_url: string | null }>();
    const target = row?.favicon_url?.trim() || FAVICON_FALLBACK;
    return new Response(null, {
      status: 307,
      headers: {
        Location: target,
        "Cache-Control": "no-store, max-age=0",
        Pragma: "no-cache",
        Expires: "0",
        "x-rn-cache": "EDGE:brand-icon",
      },
    });
  } catch (err) {
    console.error("[edge-cache] favicon lookup failed", err);
    return null;
  }
}

function normaliseQuery(url: URL): { search: string } | null {
  if (!url.search) return { search: "" };
  const allowed = ALLOWED_QUERY[url.pathname];
  const kept: [string, string][] = [];
  for (const [key, value] of url.searchParams) {
    const lower = key.toLowerCase();
    if (lower.startsWith("utm_") || TRACKING_PARAMS.has(lower)) continue;
    const rule = allowed?.[key];
    if (!rule || !rule.test(value) || kept.some(([k]) => k === key)) return null;
    kept.push([key, value]);
  }
  kept.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return { search: kept.length ? `?${new URLSearchParams(kept).toString()}` : "" };
}

function startsWithAny(path: string, prefixes: string[]): boolean {
  for (const p of prefixes) if (path.startsWith(p)) return true;
  return false;
}
